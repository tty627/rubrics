"""通用维度词表 —— 跨题可复用的评价维度，供步骤 13 按维度聚合失败模式。

**为什么要词表**：早先每题由模型现场生成维度名，全量出现 1385 种
（如「概念定义与业务实质区分」「后续结转去向与时点辨析」），
导致设计文档 §13「按 perspective 标签聚合，天然得到失败模式分布」做不了
—— 1385 种没法统计。

词表不是凭空拍的，是从那 1385 种维度名的高频语义词归纳来的：
  准确性 428 · 完整性 114 · 严密性/推导 87 · 清晰度 159 · 边界条件 68 · 规范 29

**准则内容仍保持题目专属**，只有维度名收敛。这两件事不冲突：
维度回答「这条准则测的是哪一类能力」，准则回答「本题具体要答出什么」。
"""

# 维度定义。key 是写进 schema 的 dimension 值。
# 顺序即优先级：判定时若一条准则可归多类，取靠前的（越靠前越接近"答对没答对"）。
DIMENSIONS = {
    '指令遵循能力': '是否按题目明确要求的格式、范围、约束作答（如指定输出格式、指定用某方法）',
    '知识正确性': '陈述的事实、概念、定义、数值是否与该领域共识一致',
    '答案准确性': '对有唯一解或标准答案的题，最终结论是否正确',
    '要点完整性': '题目要求覆盖的关键点是否都答到，有无遗漏子问题',
    '推理严密性': '推导过程、因果链、论证步骤是否成立，有无跳步或循环论证',
    '机理解释深度': '是否解释了「为什么」而非只给结论（机制、原理、成因）',
    '边界与前提': '是否说明适用条件、前提假设、例外情形、失效边界',
    '方案可操作性': '给出的方法、步骤、参数是否具体到可执行',
    '风险与局限': '是否指出方案的代价、副作用、局限或需注意事项',
    '误区澄清': '是否主动辨析易混概念、纠正常见错误认知',
    '表达清晰度': '结构是否清楚、结论是否明确无歧义、有无冗余',
    '证据与出处': '关键论断是否给出依据、来源、引用或可核验的支撑',
}

# 兜底：长尾学科确实归不进上表时用。应尽量避免，占比高说明词表需扩充。
FALLBACK = '其他'

VALID = set(DIMENSIONS) | {FALLBACK}


def prompt_block():
    """给 LLM 的维度清单，供 prompt 内联。"""
    lines = ['【可选维度】只能从下列维度中选，不要自造：']
    for name, desc in DIMENSIONS.items():
        lines.append(f'- {name}：{desc}')
    lines.append(f'- {FALLBACK}：确实不属于以上任何一类时才用')
    return '\n'.join(lines)


def normalize(name):
    """把模型返回的维度名收敛到词表。返回 (维度名, 是否命中词表)。"""
    if not name:
        return FALLBACK, False
    s = str(name).strip()
    if s in VALID:
        return s, s != FALLBACK
    # 模型常返回近似写法（如「知识正确性判定」），用包含关系兜一层
    for k in DIMENSIONS:
        if k in s or s in k:
            return k, True
    return FALLBACK, False
